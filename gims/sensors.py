"""
Моделі похибок вимірювальних каналів.

Це ядро дослідження. Ідея: набір даних AGC містить показання дорогих
промислових датчиків — ми вважаємо їх «істинним значенням» (опорним сигналом).
Потім пропускаємо ці дані через модель нашого реального вимірювального каналу
(бюджетний датчик + АЦП ESP32) і отримуємо те, що виміряв би наш прилад.
Різниця між прогнозом за «чистими» і за «спотвореними» даними і є предметом
дослідження.

Модель каналу — послідовність фізично осмислених перетворень:

    істинне значення
      -> методична похибка (датчик міряє не зовсім ту величину)
      -> інерційність датчика (аперіодична ланка 1-го порядку)
      -> перехресна чутливість (напр. SGP30 залежить від вологості)
      -> мультиплікативна похибка (похибка коеф. перетворення)
      -> адитивне систематичне зміщення (похибка калібрування)
      -> дрейф у часі (старіння, втрата нульової лінії)
      -> випадковий шум
      -> квантування (роздільна здатність АЦП/датчика)
      -> обмеження діапазону вимірювань
      -> відмови (пропуски відліків, «залипання» значення)
      = показання нашого датчика

ВАЖЛИВО про числа нижче. Частину параметрів узято прямо з документації
виробника (позначено source="datasheet"), частину — експертна оцінка, бо
виробник її не нормує (source="estimate"). Для роботи паспортні значення треба
обов'язково підтвердити посиланням на документацію, а експертні — або
обґрунтувати посиланням на публікації з повірки цих датчиків, або чесно
описати як прийняте припущення.
"""
from __future__ import annotations

from dataclasses import dataclass, field, replace

import numpy as np


def _first_order_lag(x: np.ndarray, a: float) -> np.ndarray:
    """Аперіодична ланка 1-го порядку: y[i] = a*y[i-1] + (1-a)*x[i].

    Реалізовано без scipy, щоб модуль лишався незалежним від важких
    залежностей. Для рядів у десятки тисяч відліків швидкості достатньо.
    """
    y = np.empty_like(x)
    acc = x[0]
    one_minus_a = 1.0 - a
    for i in range(x.size):
        acc = a * acc + one_minus_a * x[i]
        y[i] = acc
    return y


@dataclass
class ChannelErrorSpec:
    """Модель похибки одного вимірювального каналу."""

    name: str
    unit: str
    sensor: str

    # --- випадкова складова ------------------------------------------------
    noise_sigma: float = 0.0        # СКВ адитивного шуму, в одиницях вимірювання
    noise_sigma_rel: float = 0.0    # СКВ відносного шуму, частка від значення

    # --- систематична складова ---------------------------------------------
    # bias_sigma — розкид зміщення між примірниками датчиків: у кожного
    # конкретного примірника своє зміщення, стале в часі
    bias: float = 0.0               # відоме фіксоване зміщення
    bias_sigma: float = 0.0         # СКВ зміщення по сукупності примірників
    gain_err_sigma: float = 0.0     # СКВ похибки коефіцієнта перетворення

    # --- нестабільність у часі ----------------------------------------------
    drift_per_day: float = 0.0      # лінійний дрейф, одиниць/добу
    drift_rw_sigma: float = 0.0     # випадкове блукання нульової лінії, од./крок

    # --- дискретизація і діапазон -------------------------------------------
    resolution: float = 0.0         # квант (роздільна здатність), 0 = немає
    clip_min: float | None = None
    clip_max: float | None = None

    # --- динамічні властивості ----------------------------------------------
    tau_s: float = 0.0              # стала часу датчика, с

    # --- методична (структурна) похибка --------------------------------------
    # measurand_gain — частка динаміки вимірюваної величини, яка реально
    # проходить у показання. Значення 1.0 означає, що датчик міряє саме ту
    # величину, яка потрібна. Значення <1 означає, що датчик міряє щось інше,
    # лише частково пов'язане зі шуканою величиною. Це НЕ шум і не зміщення —
    # це похибка методу вимірювання, її не можна усунути ні калібруванням, ні
    # фільтрацією.
    measurand_gain: float = 1.0

    # state_gain — коефіцієнт перетворення залежить від зовнішнього стану
    # (стовпець, поріг, множник при перевищенні порога). Потрібен для випадку,
    # коли спектральна характеристика датчика не збігається зі спектром
    # джерела: наприклад, при увімкненому світлодіодному досвічуванні.
    state_gain: tuple[str, float, float] | None = None

    # --- перехресна чутливість ----------------------------------------------
    # {ім'я_іншого_каналу: (коефіцієнт, опорне_значення)}
    # ефект = коефіцієнт * (значення_іншого_каналу - опорне_значення)
    cross: dict[str, tuple[float, float]] = field(default_factory=dict)

    # --- відмови вимірювального каналу ---------------------------------------
    dropout_prob: float = 0.0       # ймовірність втрати відліку (NaN)
    stuck_prob: float = 0.0         # ймовірність входу в режим «залипання»
    stuck_mean_len: int = 12        # середня тривалість залипання, відліків

    source: str = "estimate"        # datasheet | estimate | mixed
    note: str = ""

    # ----------------------------------------------------------------------
    def scaled(self, k: float) -> "ChannelErrorSpec":
        """Масштабувати всі складові похибки в k разів.

        k=0   — ідеальний датчик (потрібен як опорна точка досліду)
        k=1   — паспортна похибка
        k=3   — сильно деградований/розлагоджений канал

        Не масштабуються: роздільна здатність і діапазон — це конструктивні
        властивості датчика, а не величина похибки.
        """
        return replace(
            self,
            noise_sigma=self.noise_sigma * k,
            noise_sigma_rel=self.noise_sigma_rel * k,
            bias=self.bias * k,
            bias_sigma=self.bias_sigma * k,
            gain_err_sigma=self.gain_err_sigma * k,
            drift_per_day=self.drift_per_day * k,
            drift_rw_sigma=self.drift_rw_sigma * k,
            cross={ch: (c * k, ref) for ch, (c, ref) in self.cross.items()},
            dropout_prob=min(1.0, self.dropout_prob * k),
            stuck_prob=min(1.0, self.stuck_prob * k),
            # Методична похибка теж має зникати при k=0: ідеальний канал міряє
            # рівно ту величину, яка потрібна
            measurand_gain=1.0 - k * (1.0 - self.measurand_gain),
            state_gain=(
                None
                if self.state_gain is None
                else (
                    self.state_gain[0],
                    self.state_gain[1],
                    1.0 - k * (1.0 - self.state_gain[2]),
                )
            ),
        )

    def only(self, *components: str) -> "ChannelErrorSpec":
        """Лишити тільки вказані складові похибки, решту обнулити.

        Потрібно для досліду E3 — розкладання внеску кожного джерела
        похибки окремо. Допустимі імена:
        noise, bias, drift, quant, lag, cross, faults, method
        """
        allowed = set(components)
        kw: dict = {}
        if "method" not in allowed:
            kw.update(measurand_gain=1.0, state_gain=None)
        if "noise" not in allowed:
            kw.update(noise_sigma=0.0, noise_sigma_rel=0.0)
        if "bias" not in allowed:
            kw.update(bias=0.0, bias_sigma=0.0, gain_err_sigma=0.0)
        if "drift" not in allowed:
            kw.update(drift_per_day=0.0, drift_rw_sigma=0.0)
        if "quant" not in allowed:
            kw.update(resolution=0.0)
        if "lag" not in allowed:
            kw.update(tau_s=0.0)
        if "cross" not in allowed:
            kw.update(cross={})
        if "faults" not in allowed:
            kw.update(dropout_prob=0.0, stuck_prob=0.0)
        return replace(self, **kw)

    # ----------------------------------------------------------------------
    def corrupt(
        self,
        x_true: np.ndarray,
        dt_s: float,
        rng: np.random.Generator,
        cross_values: dict[str, np.ndarray] | None = None,
    ) -> np.ndarray:
        """Пропустити істинний сигнал через модель вимірювального каналу.

        x_true       — опорний (істинний) сигнал
        dt_s         — крок дискретизації за часом, с
        rng          — генератор випадкових чисел (для відтворюваності)
        cross_values — значення інших каналів для перехресної чутливості

        Повертає показання датчика; втрачені відліки позначені NaN.
        """
        x = np.asarray(x_true, dtype=float).copy()
        n = x.size
        cross_values = cross_values or {}

        # 0. Методична похибка: датчик міряє не зовсім ту величину.
        #    Динаміка вимірюваної величини проходить у показання лише
        #    частково, середнє значення при цьому зберігається.
        if self.measurand_gain != 1.0:
            level = float(np.nanmean(x))
            x = level + self.measurand_gain * (x - level)

        # 1. Інерційність: реальний датчик не встигає за швидкою зміною.
        if self.tau_s > 0:
            a = float(np.exp(-dt_s / self.tau_s))
            x = _first_order_lag(x, a)

        # 2. Перехресна чутливість до інших величин
        for ch, (coef, ref) in self.cross.items():
            if ch in cross_values:
                other = np.asarray(cross_values[ch], dtype=float)
                x = x + coef * (other - ref)

        # 2а. Залежність коефіцієнта перетворення від зовнішнього стану
        #     (спектральна невідповідність при увімкненому досвічуванні)
        if self.state_gain is not None:
            col, thr, factor = self.state_gain
            if col in cross_values:
                active = np.asarray(cross_values[col], dtype=float) > thr
                x = np.where(active, x * factor, x)

        # 3. Мультиплікативна похибка (похибка коеф. перетворення).
        #    Розігрується один раз на весь прогін — це властивість примірника.
        if self.gain_err_sigma > 0:
            x = x * (1.0 + rng.normal(0.0, self.gain_err_sigma))

        # 4. Адитивне систематичне зміщення (похибка калібрування)
        if self.bias or self.bias_sigma:
            x = x + self.bias + rng.normal(0.0, self.bias_sigma)

        # 5. Дрейф у часі: детермінована частина + випадкове блукання
        if self.drift_per_day:
            t_days = np.arange(n) * dt_s / 86400.0
            x = x + self.drift_per_day * t_days
        if self.drift_rw_sigma:
            x = x + np.cumsum(rng.normal(0.0, self.drift_rw_sigma, n))

        # 6. Випадковий шум: абсолютна і відносна складові
        if self.noise_sigma:
            x = x + rng.normal(0.0, self.noise_sigma, n)
        if self.noise_sigma_rel:
            x = x + rng.normal(0.0, self.noise_sigma_rel * np.abs(x))

        # 7. Квантування за роздільною здатністю
        if self.resolution:
            x = np.round(x / self.resolution) * self.resolution

        # 8. Обмеження діапазоном вимірювань датчика
        if self.clip_min is not None or self.clip_max is not None:
            x = np.clip(x, self.clip_min, self.clip_max)

        # 9. Відмови каналу: «залипання» значення (датчик віддає те саме)
        if self.stuck_prob > 0:
            x = self._apply_stuck(x, rng)

        # 10. Відмови каналу: втрата відліку (помилка CRC, тайм-аут шини)
        if self.dropout_prob > 0:
            lost = rng.random(n) < self.dropout_prob
            x = np.where(lost, np.nan, x)

        return x

    def _apply_stuck(self, x: np.ndarray, rng: np.random.Generator) -> np.ndarray:
        """Змоделювати зависання датчика: повтор останнього значення.

        Двостановий марковський ланцюг: із нормального режиму з імовірністю
        stuck_prob переходимо в залипання, виходимо з нього з імовірністю
        1/stuck_mean_len за крок.
        """
        y = x.copy()
        p_exit = 1.0 / max(1, self.stuck_mean_len)
        stuck = False
        held = x[0]
        for i in range(x.size):
            if stuck:
                y[i] = held
                if rng.random() < p_exit:
                    stuck = False
            elif rng.random() < self.stuck_prob:
                stuck = True
                held = y[i - 1] if i > 0 else x[0]
                y[i] = held
        return y


