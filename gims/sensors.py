def corrupt_frame(
    df,
    dt_s: float,
    rng: np.random.Generator,
    scale: float = 1.0,
    only: tuple[str, ...] | None = None,
    channels: list[str] | None = None,
    overrides: dict[str, ChannelErrorSpec] | None = None,
):
    """Пропустити весь набір каналів через моделі похибок.

    df        — таблиця з «істинними» значеннями (дані AGC)
    scale     — множник величини похибки (дослід E2)
    only      — лишити тільки вказані складові похибки (дослід E3)
    overrides — замінити модель окремого каналу іншою (порівняння датчиків)

    Повертає нову таблицю з показаннями наших датчиків.
    """
    import pandas as pd

    channels = channels or [c for c in SENSOR_SPECS if c in df.columns]
    overrides = overrides or {}
    # Перехресні ефекти рахуємо від істинних значень, щоб не тягнути похибку
    # одного каналу в інший через зворотний зв'язок
    cross_values = {c: df[c].to_numpy(dtype=float) for c in df.columns}

    out = pd.DataFrame(index=df.index)
    for ch in channels:
        spec = overrides.get(ch, SENSOR_SPECS[ch])
        if only is not None:
            spec = spec.only(*only)
        spec = spec.scaled(scale)
        out[ch] = spec.corrupt(df[ch].to_numpy(dtype=float), dt_s, rng, cross_values)
    return out
